-- Create local users inside pluggable databases: PDB_Piasek_1, PDB_Piasek_2, PDB_Bazan_3
-- Each user has a dedicated tablespace and basic privileges (CONNECT, RESOURCE)
-- Users: user_1_169828, user_2_169828, user_3_176768
-- Tablespaces: Piasek_1_TS, Piasek_2_TS, Bazan_3_TS


ALTER SESSION SET "_oracle_script" = true;


-- PDB_Piasek_1
ALTER SESSION SET CONTAINER = PDB_Piasek_1;

CREATE USER user_1_169828 IDENTIFIED BY haslo
DEFAULT TABLESPACE Piasek_1_TS
QUOTA UNLIMITED ON Piasek_1_TS;
GRANT CREATE VIEW, CREATE PROCEDURE TO user_1_169828;
GRANT CREATE SESSION TO user_1_169828;
GRANT CREATE TABLE TO user_1_169828;
GRANT CREATE PROCEDURE TO user_1_169828;
GRANT CREATE SEQUENCE TO user_1_169828;
GRANT CREATE SYNONYM TO user_1_169828;
GRANT CREATE TRIGGER TO user_1_169828;
ALTER USER user_1_169828 ACCOUNT UNLOCK;
GRANT CONNECT, RESOURCE TO user_1_169828;
GRANT CREATE MATERIALIZED VIEW TO user_1_169828;


-- PDB_Piasek_2
ALTER SESSION SET CONTAINER = PDB_Piasek_2;

